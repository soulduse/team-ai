#!/usr/bin/env python3
"""Generate src/font-cjk.ts: bitmaps for what the 9x18 Menlo set (src/font.ts) lacks.

Korean (all Hangul syllables and jamo), Japanese (kana, JIS X 0208 kanji),
KS X 1001 hanja, CJK punctuation, fullwidth forms and the narrow symbol blocks
(Latin-1, punctuation, arrows, math, box drawing, blocks, shapes, braille),
taken from GNU Unifont 16x16 / 8x16 bitmaps (SIL OFL 1.1 or GPL-2.0+ with the
font embedding exception). Kanji and kana use the Japanese Unifont-JP variant.
Glyphs already in src/font.ts are skipped so ASCII output is unchanged.

The rows are deflated so the committed file stays small; src/png.ts inflates
them on first use with node:zlib. Build-time only: needs Pillow and Unifont
(`apt install fonts-unifont`, or pass the two .otf paths as arguments).
"""
import base64, re, sys, zlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parent.parent
base = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/opentype/unifont/unifont.otf"
jp = sys.argv[2] if len(sys.argv) > 2 else "/usr/share/fonts/opentype/unifont/unifont_jp.otf"
fonts = {"base": ImageFont.truetype(base, 16), "jp": ImageFont.truetype(jp, 16)}

have = set(re.search(r"GLYPHS = '((?:[^'\\]|\\.)*)'", (root / "src/font.ts").read_text()).group(1).encode().decode("unicode_escape").encode("latin1").decode())

def span(a, b): return [chr(c) for c in range(a, b + 1)]
def encodable(ch, enc):
    try: return len(ch.encode(enc)) == 2
    except UnicodeEncodeError: return False

chars = []
for a, b in [(0xA1, 0xFF), (0x2010, 0x205E), (0x2190, 0x21FF), (0x2200, 0x22FF), (0x2300, 0x23FF),
             (0x2460, 0x24FF), (0x2500, 0x25FF), (0x2600, 0x26FF), (0x2700, 0x27BF), (0x2800, 0x28FF),
             (0x1100, 0x11FF), (0x3000, 0x303F), (0x3040, 0x30FF), (0x3130, 0x318F), (0x31F0, 0x31FF),
             (0x3200, 0x32FF), (0xAC00, 0xD7A3), (0xFF01, 0xFFEE)]:
    chars += span(a, b)
chars += [c for c in span(0x4E00, 0x9FFF) if encodable(c, "euc_jp") or encodable(c, "euc_kr")]

def is_jp(c):
    o = ord(c); return 0x3040 <= o <= 0x30FF or 0x31F0 <= o <= 0x31FF or 0x4E00 <= o <= 0x9FFF

narrow, wide, n_rows, w_rows = [], [], bytearray(), bytearray()
for c in chars:
    if c in have or c.isspace(): continue
    font = fonts["jp" if is_jp(c) else "base"]
    adv = round(font.getlength(c))
    if adv not in (8, 16): continue
    img = Image.new("L", (adv, 16), 0)
    ImageDraw.Draw(img).text((0, 0), c, font=font, fill=255)
    if not img.getbbox(): continue  # Unifont has no glyph: leave it to the fallback box
    px = img.load(); rows = bytearray()
    for y in range(16):
        bits = 0
        for x in range(adv):
            if px[x, y] >= 128: bits |= 1 << (15 - x)
        rows += bits.to_bytes(2, "big")
    (narrow if adv == 8 else wide).append(c); (n_rows if adv == 8 else w_rows).extend(rows)

def pack(b): return base64.b64encode(zlib.compress(bytes(b), 9)).decode()
def lit(s): return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"
out = root / "src" / "font-cjk.ts"
out.write_text(
    "// Generated by scripts/gen-font-cjk.py — do not edit by hand.\n"
    "// GNU Unifont glyphs (SIL OFL 1.1), 16 rows each of big-endian uint16, bit 15\n"
    "// leftmost; narrow glyphs are 8 columns, wide 16. Rows are zlib-deflated and\n"
    "// base64-encoded; glyph order matches each string.\n"
    "export const UNIFONT_HEIGHT = 16;\n"
    f"export const NARROW_GLYPHS = {lit(''.join(narrow))};\n"
    f"export const NARROW_BITMAP = '{pack(n_rows)}';\n"
    f"export const WIDE_GLYPHS = {lit(''.join(wide))};\n"
    f"export const WIDE_BITMAP = '{pack(w_rows)}';\n",
    encoding="utf-8",
)
print(f"wrote {out}: {len(narrow)} narrow, {len(wide)} wide, {out.stat().st_size} bytes", file=sys.stderr)
